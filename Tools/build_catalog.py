import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PATH = os.path.join(ROOT, "Resources", "Catalog.json")
old = json.load(open(PATH))
old_groups = {g["key"]: g for s in old["sections"] for g in s["groups"]}

def opts(items):
    return [{"id": i, "name": n, "text": t} for i, n, t in items]

def keep(key, drop=()):
    return [o for o in old_groups[key]["options"] if o["id"] not in drop]

def pick(key, ids):
    by_id = {o["id"]: o for o in old_groups[key]["options"]}
    return [by_id[i] for i in ids]

def group(key, name, icon, multi, options, hint=None, template=None, edit_template=None):
    g = {"key": key, "name": name, "icon": icon, "multi": multi, "options": options}
    if hint: g["hint"] = hint
    if template: g["template"] = template
    if edit_template: g["editTemplate"] = edit_template
    return g

